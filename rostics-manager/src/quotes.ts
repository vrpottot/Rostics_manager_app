/** Порядковый номер дня в году (1..366) по локальной дате. */
function dayOfYear(d: Date): number {
  const start = new Date(d.getFullYear(), 0, 0);
  const diff = d.getTime() - start.getTime();
  return Math.floor(diff / 86400000);
}

/** Фраза на сегодня — одна и та же весь день, меняется в полночь. */
export function dailyQuote(date: Date = new Date()): string {
  return DAILY_QUOTES[dayOfYear(date) % DAILY_QUOTES.length];
}
